// Einheitlicher Zugriff ueber alle Bestaende
function getItemById(id) {
  return (
    HOTELS.find((h) => h.id === id) ||
    APARTMENTS.find((a) => a.id === id) ||
    CARS.find((c) => c.id === id) ||
    FLIGHTS.find((f) => f.id === id) ||
    null
  );
}

function itemPrice(item) {
  if (item.pricePerNight) return item.pricePerNight;
  if (item.pricePerDay) return item.pricePerDay;
  return item.price || 0;
}

function itemTitle(item) {
  return item.name || item.model || `${item.airline} ${item.fromCode}–${item.toCode}`;
}
